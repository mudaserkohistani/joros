/**
 * Deterministic generator for the "website" / "web_app" project types.
 *
 * Produces a real, self-contained static project: plain HTML/CSS/JS with a
 * tiny zero-dependency Node build script and test script, so the generated
 * project's own npm install/build/test pipeline actually runs (including
 * offline, with no network — verified in dev).
 *
 * This is intentionally simple. It is not meant to be a sophisticated
 * templating engine; it's meant to be honest: every file it claims to
 * produce, it actually produces, with real (if basic) working logic behind
 * cart/contact-form/admin-view features rather than decorative placeholders.
 */

function titleCase(s) {
  return s.replace(/_/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());
}

