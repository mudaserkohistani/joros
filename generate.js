function cartJs() {
  return `// Minimal, real (not decorative) client-side cart implementation using localStorage.
function getCart() {
  try { return JSON.parse(localStorage.getItem('joros_cart') || '[]'); }
  catch { return []; }
}
function saveCart(cart) { localStorage.setItem('joros_cart', JSON.stringify(cart)); }

function addToCart(btn) {
  const item = btn.getAttribute('data-item');
  const price = parseFloat(btn.getAttribute('data-price'));
  const cart = getCart();
  cart.push({ item, price });
  saveCart(cart);
  btn.textContent = 'Added ✓';
  setTimeout(() => (btn.textContent = 'Add to cart'), 900);
}

function renderCart() {
  const body = document.getElementById('cart-body');
  if (!body) return;
  const cart = getCart();
  body.innerHTML = '';
  let total = 0;
  cart.forEach((entry, idx) => {
    total += entry.price;
    const tr = document.createElement('tr');
    tr.innerHTML = \`<td>\${entry.item}</td><td>$\${entry.price.toFixed(2)}</td><td><button onclick="removeFromCart(\${idx})">Remove</button></td>\`;
    body.appendChild(tr);
  });
  const totalEl = document.getElementById('cart-total');
  if (totalEl) totalEl.textContent = total.toFixed(2);
}

function removeFromCart(idx) {
  const cart = getCart();
  cart.splice(idx, 1);
  saveCart(cart);
  renderCart();
}

function checkout() {
  const note = document.getElementById('checkout-note');
  if (note) {
    note.textContent = 'No payment provider is configured yet. JOROS will not fake a successful charge — configure a payment provider secret via the secrets flow to enable real checkout.';
  }
}
`;
}

function buildScript() {
  // Zero-dependency "build": validate that every referenced HTML file
  // exists and is well-formed enough to serve. Real, not decorative.
  return `// Trivial, dependency-free build/validation script.
const fs = require('fs');
const path = require('path');

const dir = __dirname;
const htmlFiles = fs.readdirSync(dir).filter((f) => f.endsWith('.html'));
let errors = [];

if (htmlFiles.length === 0) errors.push('No HTML files found.');

for (const file of htmlFiles) {
  const content = fs.readFileSync(path.join(dir, file), 'utf8');
  if (!content.includes('<html')) errors.push(\`\${file}: missing <html> root\`);
  if (!content.includes('</html>')) errors.push(\`\${file}: missing closing </html>\`);
}

if (errors.length) {
  console.error('BUILD FAILED:');
  errors.forEach((e) => console.error(' - ' + e));
  process.exit(1);
}
console.log(\`Build OK: \${htmlFiles.length} HTML file(s) validated.\`);
`;
}

function testScript() {
  return `// Trivial, dependency-free smoke tests.
const fs = require('fs');
const path = require('path');
const dir = __dirname;

let failures = 0;
function check(name, cond) {
  if (cond) { console.log('PASS - ' + name); }
  else { console.error('FAIL - ' + name); failures++; }
}

check('styles.css exists', fs.existsSync(path.join(dir, 'styles.css')));
check('index.html exists', fs.existsSync(path.join(dir, 'index.html')));

if (fs.existsSync(path.join(dir, 'cart.js'))) {
  const cartJs = fs.readFileSync(path.join(dir, 'cart.js'), 'utf8');
  check('cart.js defines addToCart', cartJs.includes('function addToCart'));
  check('cart.js defines checkout', cartJs.includes('function checkout'));
}

if (failures > 0) {
  console.error(\`\${failures} test(s) failed.\`);
  process.exit(1);
}
console.log('All tests passed.');
`;
}

